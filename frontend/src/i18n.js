const common = { uz, ru, en }
const locales = { uz: "uz-UZ", ru: "ru-RU", en: "en-US" }

export function setLanguage(code) {
  if (!supportedCodes.has(code)) return
  language.value = code
  localStorage.setItem("qulay_language", code)
  document.documentElement.lang = code
  document.documentElement.dir = "ltr"
}

export function initLanguage() {
  setLanguage(language.value)
}

export function useI18n() {
  return {
    language,
    setLanguage,
    // MUHIM QOIDA: tanlangan til -> uz (asosiy) -> kalitning o'zi. Hech qachon en ga tushmaydi!
    t: (key) => common[language.value]?.[key] ?? common.uz?.[key] ?? key,
    locale: () => locales[language.value] || "uz-UZ",
  }
}

